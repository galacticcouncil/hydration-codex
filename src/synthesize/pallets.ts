// Simplified metadata format (from baseline.json - fallback)
interface ChainMetadata {
  extractedAt: string;
  source: string;
  endpoint: string;
  specName: string;
  specVersion: number;
  blockNumber: number;
  pallets: PalletMetadata[];
}

interface PalletMetadata {
  name: string;
  index: number;
  calls: string[];
  events: string[];
  storage: string[];
  constants: string[];
}

interface PalletsOptions {
  extractionsPath: string;
  outputPath: string;
}


export async function synthesizePallets(options: PalletsOptions): Promise<void> {
  const { extractionsPath, outputPath } = options;

  log.section('Pallet Documentation Generation');

  // Load detailed metadata (preferred) or fall back to baseline
  const detailedPath = join(extractionsPath, 'metadata/metadata.json');
  const baselinePath = join(extractionsPath, 'metadata/baseline.json');

  let detailedMetadata: DetailedMetadata | null = null;
  let metadata: ChainMetadata;

  if (existsSync(detailedPath)) {
    const loadedMetadata = readJSON<DetailedMetadata>(detailedPath);
    if (!loadedMetadata) {
      throw new Error('Failed to load detailed metadata.');
    }
    detailedMetadata = loadedMetadata;
    log.info(`Loaded detailed metadata: ${loadedMetadata.pallets.length} pallets with types`);
    // Create compatible ChainMetadata for legacy functions
    metadata = {
      extractedAt: loadedMetadata.extractedAt,
      source: 'hydradx',
      endpoint: '',
      specName: loadedMetadata.specName,
      specVersion: loadedMetadata.specVersion,
      blockNumber: loadedMetadata.blockNumber,
      pallets: loadedMetadata.pallets.map(p => ({
        name: p.name,
        index: p.index,
        calls: p.calls.map(c => c.name),
        events: p.events.map(e => e.name),
        storage: p.storage.map(s => s.name),
        constants: p.constants.map(c => c.name),
      })),
    };
  } else if (existsSync(baselinePath)) {
    const loadedMetadata = readJSON<ChainMetadata>(baselinePath);
    if (!loadedMetadata) {
      throw new Error('Failed to load baseline metadata.');
    }
    metadata = loadedMetadata;
    log.warn('Using baseline metadata (no types). Run npm run extract:metadata for detailed types.');
  } else {
    throw new Error('Missing chain metadata. Run npm run extract:chain:baseline first.');
  }

  log.info(`Spec: ${metadata.specName} v${metadata.specVersion}`);

  // Load cross-reference index (v2 with canonical IDs)
  const crossRefPath = join(process.env.OUTPUT_PATH || './docs-site/docs', '../static/cross-references.json');
  let crossRef: CanonicalIndex | null = null;
  if (existsSync(crossRefPath)) {
    crossRef = readJSON<CanonicalIndex>(crossRefPath);
    const totalEdges = crossRef?.edges?.length ?? 0;
    log.info(`Loaded cross-reference index: ${totalEdges} edges`);
  } else {
    log.warn('Cross-reference index not found. Run npm run synthesize:crossref first.');
  }

  // Load hook index for accurate category mapping
  const hookIndex = loadHookIndex(outputPath);

  // Load SDK extraction to find SDK methods that use each pallet/storage
  interface SDKMethodRef { package: string; method: string; }
  const palletToSDK = new Map<string, SDKMethodRef[]>();
  // Map: "pallet.storage_item" → [{method, package}]
  interface StorageMethodRef { method: string; package: string; }
  const storageToSDK = new Map<string, StorageMethodRef[]>();

  // Try enhanced extraction first, then fall back to regular
  const enhancedPath = join(extractionsPath, 'sdk/extraction-enhanced.json');
  const regularPath = join(extractionsPath, 'sdk/extraction.json');
  const sdkExtractionPath = existsSync(enhancedPath) ? enhancedPath : regularPath;

  if (existsSync(sdkExtractionPath)) {
    try {
      const sdkExtraction = readJSON<{
        packages: Array<{
          name: string;
          palletCalls?: {
            tx: Array<{ pallet: string; item: string; methods: string[] }>;
            query: Array<{ pallet: string; item: string; methods: string[] }>;
            consts: Array<{ pallet: string; item: string; methods: string[] }>;
          };
        }>;
      }>(sdkExtractionPath);
      if (sdkExtraction?.packages) {
        for (const pkg of sdkExtraction.packages) {
          if (!pkg.palletCalls) continue;
          const shortPkgName = pkg.name.replace('@galacticcouncil/', '');

          // Process all call types
          const allCalls = [
            ...(pkg.palletCalls.tx || []),
            ...(pkg.palletCalls.query || []),
            ...(pkg.palletCalls.consts || []),
          ];

          for (const call of allCalls) {
            const palletName = call.pallet.toLowerCase();

            // Pallet-level mapping
            if (!palletToSDK.has(palletName)) palletToSDK.set(palletName, []);
            const refs = palletToSDK.get(palletName)!;
            if (!refs.some(r => r.package === shortPkgName)) {
              refs.push({ package: shortPkgName, method: call.item });
            }

            // Storage-level mapping with package info for linking
            if (call.item && call.methods) {
              const storageKey = `${palletName}.${call.item.toLowerCase()}`;
              if (!storageToSDK.has(storageKey)) storageToSDK.set(storageKey, []);
              const storageMethods = storageToSDK.get(storageKey)!;
              for (const method of call.methods) {
                if (!storageMethods.some(m => m.method === method)) {
                  storageMethods.push({ method, package: shortPkgName });
                }
              }
            }
          }
        }
        log.info(`Loaded SDK→Pallet mappings: ${palletToSDK.size} pallets, ${storageToSDK.size} storage items`);
      }
    } catch {
      log.warn('Failed to load SDK extraction');
    }
  }

  // Load handler details and event→entity mappings from indexer extraction
  interface HandlerInfo { event: string; file: string; line: number; }
  const handlerIndex = new Map<string, HandlerInfo>();
  let indexerSource: { repo: string; commit: string } | null = null;
  let eventToHandlerMap: Record<string, { handlers: string[]; entities: string[] }> = {};
  const validEntityNames = new Set<string>(); // Track valid entity names (not enum types)
  const indexerExtractionPath = join(extractionsPath, 'indexer/extraction.json');
  if (existsSync(indexerExtractionPath)) {
    try {
      const indexerExtraction = readJSON<{
        meta: { source: { repo: string; commit: string } };
        schema?: { entities: { name: string }[] };
        handlers: { handler: string; event: string; file: string; line: number }[];
        eventToHandlerMap?: Record<string, { handlers: string[]; entities: string[] }>;
      }>(indexerExtractionPath);
      if (indexerExtraction?.meta?.source) {
        indexerSource = indexerExtraction.meta.source;
      }
      // Load valid entity names from schema
      if (indexerExtraction?.schema?.entities) {
        for (const entity of indexerExtraction.schema.entities) {
          validEntityNames.add(entity.name);
        }
        log.info(`Loaded ${validEntityNames.size} valid entity names`);
      }
      if (indexerExtraction?.handlers) {
        for (const h of indexerExtraction.handlers) {
          handlerIndex.set(h.handler, { event: h.event, file: h.file, line: h.line });
        }
        log.info(`Loaded handler index: ${handlerIndex.size} handlers`);
      }
      if (indexerExtraction?.eventToHandlerMap) {
        eventToHandlerMap = indexerExtraction.eventToHandlerMap;
        log.info(`Loaded event→entity map: ${Object.keys(eventToHandlerMap).length} events`);
      }
    } catch {
      log.warn('Failed to load indexer extraction');
    }
  }

  // Build pallet lookup maps from cross-ref edges
  const palletToHooks = new Map<string, { name: string; category: string }[]>();
  const palletToEntities = new Map<string, string[]>();

  if (crossRef?.edges) {
    const palletHooksMap = new Map<string, Map<string, { name: string; category: string }>>();
    const palletEntitiesMap = new Map<string, Set<string>>();

    for (const edge of crossRef.edges) {
      if (edge.type === 'contains') continue;

      try {
        const fromParsed = parseCanonicalId(edge.from);
        const toParsed = parseCanonicalId(edge.to);

        // UI hook → Runtime (get pallet name from target)
        if (fromParsed.layer === 'ui' && fromParsed.segments[0]?.type === 'hook' &&
            toParsed.layer === 'runtime') {
          const palletName = toParsed.segments[0].name.toLowerCase();
          const hookName = fromParsed.segments[0].name;

          // Only include hooks that exist in the hook index (have generated pages)
          const category = getHookCategory(hookName, hookIndex);
          if (!category) continue; // Skip hooks without generated pages

          if (!palletHooksMap.has(palletName)) palletHooksMap.set(palletName, new Map());
          palletHooksMap.get(palletName)!.set(hookName, { name: hookName, category });
        }

        // Indexer entity → Runtime pallet
        if (fromParsed.layer === 'indexer' && fromParsed.segments[0]?.type === 'entity' &&
            toParsed.layer === 'runtime' && toParsed.segments[0]?.type === 'pallet') {
          const palletName = toParsed.segments[0].name.toLowerCase();
          const entityName = fromParsed.segments[0].name;

          if (!palletEntitiesMap.has(palletName)) palletEntitiesMap.set(palletName, new Set());
          palletEntitiesMap.get(palletName)!.add(entityName);
        }

        // Indexer handler → Runtime event (handler handles pallet event)
        if (fromParsed.layer === 'indexer' && fromParsed.segments[0]?.type === 'handler' &&
            toParsed.layer === 'runtime' && edge.type === 'handles') {
          const palletName = toParsed.segments[0].name.toLowerCase();
          // Use the handler name as a proxy for entities (handlers often create/update entities)
          const handlerName = fromParsed.segments[0].name;

          if (!palletEntitiesMap.has(palletName)) palletEntitiesMap.set(palletName, new Set());
          // Add a marker like "via handleAssetRegistryRegistered" to show the handler
          palletEntitiesMap.get(palletName)!.add(`handler:${handlerName}`);
        }
      } catch {
        continue;
      }
    }

    // Convert to final format
    for (const [pallet, hooksMap] of palletHooksMap) {
      if (hooksMap.size > 0) {
        palletToHooks.set(pallet, Array.from(hooksMap.values()));
      }
    }
    for (const [pallet, entitiesSet] of palletEntitiesMap) {
      if (entitiesSet.size > 0) {
        palletToEntities.set(pallet, Array.from(entitiesSet));
      }
    }
  }
  log.info(`Loaded ${palletToHooks.size} pallet→UI mappings, ${palletToEntities.size} pallet→Indexer mappings`);

  // Pre-fetch workspace Cargo.toml files to find exact crate paths
  await prefetchWorkspaceMembers();

  // Create output directory
  const palletsOutputPath = join(outputPath, 'reference/pallets');
  mkdirSync(palletsOutputPath, { recursive: true });

  // Sort pallets by index
  const allPallets = [...metadata.pallets].sort((a, b) => a.index - b.index);

  // Pre-fetch docs for external pallets from GitHub
  await prefetchExternalPalletDocs(allPallets.map(p => p.name));

  log.section('Generating Pallet Pages');

  // Build detailed pallet lookup if available
  const detailedPalletMap = new Map<string, DetailedPalletMetadata>();
  if (detailedMetadata) {
    for (const p of detailedMetadata.pallets) {
      detailedPalletMap.set(p.name.toLowerCase(), p);
    }
  }

  // Generate all pallet pages
  for (const pallet of allPallets) {
    const hooksWithCategory = palletToHooks.get(pallet.name.toLowerCase()) || [];
    const entities = palletToEntities.get(pallet.name.toLowerCase()) || [];
    const sdkRefs = palletToSDK.get(pallet.name.toLowerCase()) || [];
    const detailed = detailedPalletMap.get(pallet.name.toLowerCase());
    const mdxContent = generatePalletMdx(pallet, hooksWithCategory, entities, sdkRefs, storageToSDK, metadata, detailed, handlerIndex, indexerSource, eventToHandlerMap, validEntityNames);
    const filePath = join(palletsOutputPath, `${pallet.name}.mdx`);
    writeFileSync(filePath, mdxContent);
  }

  log.success(`Generated ${allPallets.length} pallet pages`);

  // Index page is auto-generated by Docusaurus sidebar (generated-index)

  // Generate version manifest for tracking and comparison
  const manifestPath = join(outputPath, 'reference/pallets/version-manifest.json');
  const manifest = generateVersionManifest(metadata, allPallets);
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
  log.info(`Generated version manifest: ${manifestPath}`);

  log.section('Generation Complete');
  console.log(`\n  Output: ${palletsOutputPath}/`);
  console.log(`  Pages: ${allPallets.length}\n`);
}

function loadLatestExtraction<T>(baseDir: string, layer: string): T | null {
  const layerDir = join(baseDir, layer);
  if (!existsSync(layerDir)) return null;

  const files = readdirSync(layerDir).filter(f => f.endsWith('.json'));
  if (files.length === 0) return null;

  if (files.includes('extraction.json')) {
    return readJSON<T>(join(layerDir, 'extraction.json'));
  }

  const sortedFiles = files.sort((a, b) => {
    const statA = statSync(join(layerDir, a));
    const statB = statSync(join(layerDir, b));
    return statB.mtime.getTime() - statA.mtime.getTime();
  });

  return readJSON<T>(join(layerDir, sortedFiles[0]));
}

