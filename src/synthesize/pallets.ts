// Cache for hook index
let hookIndexCache: Record<string, { category: string; file: string }> | null = null;

/**
 * Load hook index generated by hooks synthesizer.
 * Falls back to 'utils' if hook not found.
 */
function loadHookIndex(outputPath: string): Record<string, { category: string; file: string }> {
  if (hookIndexCache) return hookIndexCache;

  const indexPath = join(outputPath, '../static/hook-index.json');
  if (existsSync(indexPath)) {
    try {
      const content = readFileSync(indexPath, 'utf-8');
      hookIndexCache = JSON.parse(content);
      log.info(`Loaded hook index: ${Object.keys(hookIndexCache!).length} hooks`);
      return hookIndexCache!;
    } catch {
      log.warn('Failed to load hook index, using fallback');
    }
  } else {
    log.warn('Hook index not found. Run npm run synthesize:hooks first.');
  }

  hookIndexCache = {};
  return hookIndexCache;
}

/**
 * Get hook category from index, or return null if not found.
 */
function getHookCategory(hookName: string, hookIndex: Record<string, { category: string; file: string }>): string | null {
  return hookIndex[hookName]?.category ?? null;
}

// Pallet runtime info from construct_runtime!
interface PalletRuntimeInfo {
  crateName: string;       // e.g., "pallet-collective"
  instance?: string;       // e.g., "Instance2" if using an instance
  index: number;           // Pallet index in runtime
}

// Cache for pallet-to-crate mapping from construct_runtime!
let palletToCrateCache: Map<string, PalletRuntimeInfo> | null = null;

// Parse construct_runtime! macro to get pallet name -> crate name + instance mapping
function parsePalletToCrateMapping(): Map<string, PalletRuntimeInfo> {
  if (palletToCrateCache) return palletToCrateCache;

  palletToCrateCache = new Map();
  const runtimePath = join(HYDRADX_NODE_PATH, 'runtime/hydradx/src/lib.rs');

  if (!existsSync(runtimePath)) {
    log.warn('Runtime lib.rs not found, pallet mapping unavailable');
    return palletToCrateCache;
  }

  try {
    const content = readFileSync(runtimePath, 'utf-8');

    // Find construct_runtime! macro content
    const match = content.match(/construct_runtime!\s*\(\s*pub\s+enum\s+Runtime\s*\{([\s\S]*?)\}\s*\)/);
    if (!match) {
      log.warn('construct_runtime! macro not found');
      return palletToCrateCache;
    }

    const runtimeBlock = match[1];

    // Parse each line: "PalletName: crate_path::<Instance> = index"
    // Examples:
    //   System: frame_system exclude_parts { Origin } = 1,
    //   Balances: pallet_balances = 7,
    //   TechnicalCommittee: pallet_collective::<Instance2> = 25,
    //   OmnipoolWarehouseLM: warehouse_liquidity_mining::<Instance1> = 62,
    //   Origins: pallet_custom_origins = 38,
    const palletRegex = /^\s*(\w+):\s*([\w_]+)(?:::<(\w+)>)?(?:\s+exclude_parts\s*\{[^}]*\})?\s*=\s*(\d+)/gm;

    let palletMatch;
    while ((palletMatch = palletRegex.exec(runtimeBlock)) !== null) {
      const palletName = palletMatch[1];
      const cratePath = palletMatch[2];
      const instance = palletMatch[3];  // undefined if no instance
      const index = parseInt(palletMatch[4], 10);

      // Convert underscore to hyphen for crate name lookup
      // frame_system -> frame-system, pallet_balances -> pallet-balances
      const crateName = cratePath.replace(/_/g, '-');

      palletToCrateCache.set(palletName.toLowerCase(), {
        crateName,
        instance,
        index,
      });
    }

    log.info(`Parsed ${palletToCrateCache.size} pallet-to-crate mappings from construct_runtime!`);
  } catch (err) {
    log.warn(`Failed to parse construct_runtime!: ${err}`);
  }

  return palletToCrateCache;
}

// Get just the crate name for a pallet (for backward compatibility)
function getCrateNameForPallet(palletName: string): string | undefined {
  const info = parsePalletToCrateMapping().get(palletName.toLowerCase());
  return info?.crateName;
}

// Cache for HydraDX-node git info
let hydradxGitInfo: { commit: string; branch: string } | null = null;

// Get HydraDX-node git commit and branch from the actual submodule
function getHydradxGitInfo(): { commit: string; branch: string } {
  if (hydradxGitInfo) return hydradxGitInfo;

  try {
    const commit = execSync('git rev-parse HEAD', {
      cwd: HYDRADX_NODE_PATH,
      encoding: 'utf-8',
    }).trim();

    // Get branch name (may be detached HEAD, so fallback to commit)
    let branch = 'master';
    try {
      branch = execSync('git rev-parse --abbrev-ref HEAD', {
        cwd: HYDRADX_NODE_PATH,
        encoding: 'utf-8',
      }).trim();
      if (branch === 'HEAD') {
        // Detached HEAD, try to get tag or use commit
        branch = execSync('git describe --tags --exact-match 2>/dev/null || echo ""', {
          cwd: HYDRADX_NODE_PATH,
          encoding: 'utf-8',
        }).trim() || commit.substring(0, 8);
      }
    } catch {
      branch = commit.substring(0, 8);
    }

    hydradxGitInfo = { commit, branch };
    return hydradxGitInfo;
  } catch (err) {
    // Fallback if git command fails
    hydradxGitInfo = { commit: 'master', branch: 'master' };
    return hydradxGitInfo;
  }
}

