/**
 * Pallet Documentation Synthesizer
 *
 * Generates comprehensive MDX documentation pages for all runtime pallets.
 *
 * Features:
 * - Extracts docs from README.md and lib.rs doc comments (//!)
 * - Fetches external pallet docs from GitHub (Polkadot SDK, ORML, Hyperbridge, Frontier)
 * - Parses Cargo.lock to find pallet sources and exact paths via [workspace.dependencies]
 * - Cross-references events with indexer entities ("Indexed by" links)
 * - Links to GitHub, docs.rs, crates.io, and Subscan
 *
 * Documentation Sources:
 * - HydraDX pallets: Read from local repos/hydration-node/pallets/
 * - External pallets: Fetched from GitHub using raw.githubusercontent.com
 *
 * Output: docs-site/docs/reference/pallets/*.mdx
 */

