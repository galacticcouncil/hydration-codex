// Get all possible crate names for a pallet name
// Uses construct_runtime! parsing first, then falls back to common patterns
function getCrateNamesForPallet(palletName: string): string[] {
  const name = palletName.toLowerCase().replace(/_/g, '');
  const snakeName = toSnakeCase(palletName).replace(/_/g, '-');

  const candidates: string[] = [];

  // First, check the parsed construct_runtime! mapping
  const palletToCrate = parsePalletToCrateMapping();
  const exactCrate = palletToCrate.get(name);
  if (exactCrate) {
    candidates.push(exactCrate.crateName);
  }

  // Add common patterns as fallback
  candidates.push(`pallet-${snakeName}`);      // pallet-balances
  candidates.push(`orml-${snakeName}`);        // orml-tokens
  candidates.push(snakeName);                   // ismp-parachain
  candidates.push(`${snakeName}-pallet`);      // some-pallet

  return [...new Set(candidates)]; // Remove duplicates
}

// Look up dependency info from Cargo.lock by pallet name
function getDependencyForPallet(palletName: string): DependencySource | undefined {
  const allDeps = parseAllCargoLockDependencies();
  const candidates = getCrateNamesForPallet(palletName);

  for (const crateName of candidates) {
    const dep = allDeps.get(crateName);
    if (dep) return dep;
  }

  return undefined;
}

// Cache for all dependency sources (not just pallets)
let allDependenciesCache: Map<string, DependencySource> | null = null;

// Parse ALL Cargo.lock dependencies for complete version tracking
function parseAllCargoLockDependencies(): Map<string, DependencySource> {
  if (allDependenciesCache) return allDependenciesCache;

  allDependenciesCache = new Map();
  const cargoLockPath = join(HYDRADX_NODE_PATH, 'Cargo.lock');

  if (!existsSync(cargoLockPath)) {
    log.warn('Cargo.lock not found, dependency tracking disabled');
    return allDependenciesCache;
  }

  try {
    const content = readFileSync(cargoLockPath, 'utf-8');
    const packages = content.split('[[package]]');

    for (const pkg of packages) {
      const nameMatch = pkg.match(/^name\s*=\s*"([^"]+)"/m);
      const versionMatch = pkg.match(/^version\s*=\s*"([^"]+)"/m);
      const sourceMatch = pkg.match(/^source\s*=\s*"([^"]+)"/m);

      if (!nameMatch || !versionMatch) continue;

      const crateName = nameMatch[1];
      const version = versionMatch[1];
      const sourceUrl = sourceMatch ? sourceMatch[1] : '';

      const dep: DependencySource = {
        crateName,
        version,
        sourceType: sourceUrl.startsWith('git+') ? 'git' : 'registry',
      };

      if (dep.sourceType === 'git') {
        // Parse: git+https://github.com/owner/repo?branch=xxx#commit
        const gitUrl = sourceUrl.replace('git+', '');
        dep.gitUrl = gitUrl;

        // Extract repo, branch, and commit
        const urlMatch = gitUrl.match(/https:\/\/github\.com\/([^/?#]+\/[^/?#]+)(?:\?branch=([^#]+))?(?:#([a-f0-9]+))?/);
        if (urlMatch) {
          dep.forkRepo = urlMatch[1];  // Original fork repo
          dep.branch = urlMatch[2] || 'main';
          dep.commit = urlMatch[3];    // Exact commit hash

          // Map to upstream repo for canonical display
          const repoConfig = KNOWN_REPOS[urlMatch[1]];
          dep.repo = repoConfig?.upstream || urlMatch[1];
        }
      } else {
        dep.registryUrl = sourceUrl;
      }

      allDependenciesCache.set(crateName, dep);
    }

    log.info(`Parsed ${allDependenciesCache.size} dependencies from Cargo.lock`);
  } catch (err) {
    log.warn(`Failed to parse Cargo.lock: ${err}`);
  }

  return allDependenciesCache;
}

// Parse Cargo.lock to find external pallet sources
function parseCargoLock(): Map<string, ExternalPalletSource> {
  if (externalPalletsCache) return externalPalletsCache;

  externalPalletsCache = new Map();
  const allDeps = parseAllCargoLockDependencies();

  for (const [crateName, dep] of allDeps) {
    // Process pallet-*, orml-*, and ismp-related crates from git sources
    if (dep.sourceType !== 'git') continue;
    if (!crateName.startsWith('pallet-') &&
        !crateName.startsWith('orml-') &&
        !crateName.includes('ismp')) continue;

    if (!dep.repo) continue;

    // Convert crate name to pallet name
    // pallet-ismp -> Ismp, ismp-parachain -> IsmpParachain
    // orml-tokens -> Tokens, orml-vesting -> Vesting
    let palletName = crateName
      .replace(/^pallet-/, '')
      .replace(/^orml-/, '')
      .replace(/-pallet$/, '');
    palletName = toPascalCase(palletName);

    // Build bulletproof URLs
    const cratesIoUrl = `https://crates.io/crates/${crateName}`;
    const githubUrl = `https://github.com/${dep.repo}`;

    const source: ExternalPalletSource = {
      name: crateName,
      palletName,
      version: dep.version,
      gitUrl: dep.gitUrl || '',
      repo: dep.repo,
      forkRepo: dep.forkRepo !== dep.repo ? dep.forkRepo : undefined,
      branch: dep.branch,
      commit: dep.commit,
      cratesIoUrl,
      githubUrl,
    };

    // Store by lowercase pallet name for lookup
    externalPalletsCache.set(palletName.toLowerCase(), source);
  }

  if (externalPalletsCache.size > 0) {
    log.info(`Found ${externalPalletsCache.size} external pallet sources`);
  }

  return externalPalletsCache;
}

// Get the default branch for a known repo
function getDefaultBranch(repo: string): string {
  // Most repos use 'main', some use 'master'
  const masterBranches = [
    'paritytech/polkadot-sdk',
    'open-web3-stack/open-runtime-module-library',
    'galacticcouncil/HydraDX-node',
  ];
  return masterBranches.includes(repo) ? 'master' : 'main';
}

// Pre-fetch workspace members for all unique repos to get exact paths
// Uses the ACTUAL branch/commit from Cargo.lock, not default branches
async function prefetchWorkspaceMembers(): Promise<void> {
  const externalPallets = parseCargoLock();

  // Collect unique repo@ref combinations from actual Cargo.lock sources
  // Use commit hash when available for exact reproducibility
  const repoRefs = new Set<string>();
  for (const source of externalPallets.values()) {
    // Prefer commit hash, fallback to branch from Cargo.lock
    const ref = source.commit || source.branch || 'main';
    const repo = source.forkRepo || source.repo;
    repoRefs.add(`${repo}@${ref}`);
  }

  // Fetch workspace members for each repo@ref in parallel
  const fetchPromises = Array.from(repoRefs).map(key => {
    const [repo, ref] = key.split('@');
    return fetchWorkspaceMembers(repo, ref);
  });

  await Promise.all(fetchPromises);
}

// Pallet source information
interface PalletSource {
  repo: 'hydradx' | 'polkadot-sdk' | 'orml' | 'cumulus' | 'external';
  path: string;
  cratesIoUrl?: string;   // crates.io URL for external pallets
  githubUrl?: string;     // GitHub repo URL for external pallets
  crateName?: string;     // Original crate name
  version?: string;       // Crate version
  commit?: string;        // Exact commit hash
  branch?: string;        // Branch name
  forkRepo?: string;      // Fork repo if using a fork
  instance?: string;      // Instance name (e.g., "Instance2") for multi-instance pallets
}

// Determine the source repository for a pallet
// Uses construct_runtime! parsing and Cargo.lock for accurate detection
// Paths are resolved from workspace Cargo.toml files (no hardcoded mappings)
function getPalletSource(palletName: string): PalletSource {
  const name = palletName.toLowerCase().replace(/_/g, '');
  const snakeName = toSnakeCase(palletName);

  // Get runtime info from construct_runtime! (includes instance info)
  const palletToCrate = parsePalletToCrateMapping();
  const runtimeInfo = palletToCrate.get(name);
  const crateName = runtimeInfo?.crateName;
  const instance = runtimeInfo?.instance;

  // Look up the crate in Cargo.lock
  const allDeps = parseAllCargoLockDependencies();
  const dep = crateName ? allDeps.get(crateName) : undefined;

  // If crate found in Cargo.lock with git source
  if (dep && dep.sourceType === 'git' && dep.repo) {
    // Determine repo type and path based on upstream repo
    const upstreamRepo = dep.repo;
    const forkRepo = dep.forkRepo || upstreamRepo;
    const branch = dep.branch || 'main';
    // Use commit for workspace lookup (matches prefetchWorkspaceMembers cache key)
    const workspaceRef = dep.commit || branch;

    // Polkadot SDK pallets - get path from workspace Cargo.toml
    if (upstreamRepo === 'paritytech/polkadot-sdk') {
      // Try to get path from pre-fetched workspace members
      const workspacePath = getWorkspacePath(forkRepo, workspaceRef, dep.crateName);
      // Fallback: derive path from crate name
      let fallbackPath: string;
      if (dep.crateName.startsWith('cumulus-pallet-')) {
        // cumulus-pallet-parachain-system -> cumulus/pallets/parachain-system
        fallbackPath = `cumulus/pallets/${dep.crateName.replace('cumulus-pallet-', '')}`;
      } else if (dep.crateName.startsWith('frame-')) {
        fallbackPath = `substrate/frame/${dep.crateName.replace('frame-', '')}`;
      } else {
        fallbackPath = `substrate/frame/${dep.crateName.replace('pallet-', '')}`;
      }
      const path = workspacePath || fallbackPath;

      return {
        repo: 'polkadot-sdk',
        path,
        crateName: dep.crateName,
        version: dep.version,
        commit: dep.commit,
        branch: dep.branch,
        forkRepo,  // Use the fallback variable
        instance,
      };
    }

    // ORML pallets - get path from workspace Cargo.toml
    if (upstreamRepo === 'open-web3-stack/open-runtime-module-library') {
      // Try to get path from pre-fetched workspace members
      const workspacePath = getWorkspacePath(forkRepo, workspaceRef, dep.crateName);
      // Fallback: orml-tokens -> tokens
      const fallbackPath = dep.crateName.replace('orml-', '');
      const path = workspacePath || fallbackPath;

      return {
        repo: 'orml',
        path,
        crateName: dep.crateName,
        version: dep.version,
        commit: dep.commit,
        branch: dep.branch,
        forkRepo,  // Use the fallback variable
        instance,
      };
    }

    // Other external pallets (Hyperbridge, Frontier, etc.)
    // Try to get path from workspace Cargo.toml
    const workspacePath = getWorkspacePath(forkRepo, workspaceRef, dep.crateName);

    return {
      repo: 'external',
      path: workspacePath || '',
      cratesIoUrl: `https://crates.io/crates/${dep.crateName}`,
      githubUrl: `https://github.com/${upstreamRepo}`,
      crateName: dep.crateName,
      version: dep.version,
      commit: dep.commit,
      branch: dep.branch,
      forkRepo,  // Use the fallback variable
      instance,
    };
  }

  // If crate found but no source or is local -> it's a HydraDX pallet
  // Also check if the pallet directory exists locally
  if (crateName) {
    // Try common paths for HydraDX pallets
    const baseName = crateName.replace(/^pallet-/, '').replace(/^warehouse-/, '');
    const possiblePaths = [
      `pallets/${crateName.replace(/^pallet-/, '').replace(/-/g, '_')}`,
      `pallets/${crateName.replace(/^pallet-/, '')}`,
      `pallets/${baseName}`,  // warehouse-liquidity-mining -> liquidity-mining
      `pallets/${baseName.replace(/-/g, '_')}`,
      `pallets/${snakeName}`,
      `runtime/hydradx/src/governance`,  // For pallet_custom_origins
    ];

    for (const path of possiblePaths) {
      if (existsSync(join(HYDRADX_NODE_PATH, path))) {
        return { repo: 'hydradx', path, crateName, instance };
      }
    }
  }

  // Check external pallets cache (for legacy compatibility)
  const externalPallets = parseCargoLock();
  const external = externalPallets.get(name);
  if (external) {
    return {
      repo: 'external',
      path: '',
      cratesIoUrl: external.cratesIoUrl,
      githubUrl: external.githubUrl,
      crateName: external.name,
      version: external.version,
      commit: external.commit,
      branch: external.branch,
      forkRepo: external.forkRepo,
      instance,
    };
  }

  // Default to HydraDX for unknown pallets
  return { repo: 'hydradx', path: `pallets/${snakeName}`, instance };
}

// Pallet links structure
interface PalletLinks {
  cratesIo?: string;    // crates.io page (versions, docs link, repo link)
  docsRs?: string;      // docs.rs source viewer (direct to source code)
  github: string;       // GitHub repo or path (at exact commit if available)
  // Version tracking info
  version?: string;     // Crate version
  commit?: string;      // Exact commit hash
  branch?: string;      // Branch name
  forkRepo?: string;    // Fork repo if using a fork
  instance?: string;    // Instance name (e.g., "Instance2") for multi-instance pallets
  crateName?: string;   // Crate name (for display when different from pallet name)
}

// Build links for a pallet - includes crates.io, docs.rs source, and GitHub
// Uses exact commit hashes from Cargo.lock for reproducible links
function buildPalletLinks(palletName: string): PalletLinks {
  const source = getPalletSource(palletName);

  switch (source.repo) {
    case 'external': {
      // External crates: use crates.io + docs.rs source viewer + GitHub with path
      const externalPallets = parseCargoLock();
      const name = palletName.toLowerCase().replace(/_/g, '');
      const external = externalPallets.get(name);

      let githubUrl = source.githubUrl || 'https://github.com/galacticcouncil/HydraDX-node';

      // Try to get exact path from workspace Cargo.toml or use known patterns
      if (external && source.crateName) {
        // Use the ACTUAL repo and ref from Cargo.lock (commit or branch)
        const actualRepo = external.forkRepo || external.repo;
        const actualRef = external.commit || external.branch || 'main';

        // Get path from workspace using the exact ref we're linking to
        let path = getWorkspacePath(actualRepo, actualRef, source.crateName);

        // If not found in workspace, use known repo patterns
        if (!path) {
          if (external.repo === 'open-web3-stack/open-runtime-module-library') {
            // ORML: orml-tokens -> tokens/
            path = source.crateName.replace(/^orml-/, '');
          } else if (external.repo === 'paritytech/polkadot-sdk' && source.crateName.startsWith('pallet-')) {
            // Polkadot SDK fallback: pallet-foo -> substrate/frame/foo
            path = `substrate/frame/${source.crateName.replace(/^pallet-/, '')}`;
          } else if (external.repo === 'polytope-labs/hyperbridge') {
            // Hyperbridge fallback patterns
            if (source.crateName.startsWith('pallet-')) {
              // pallet-ismp -> modules/pallets/ismp
              path = `modules/pallets/${source.crateName.replace(/^pallet-/, '')}`;
            } else if (source.crateName === 'ismp-parachain') {
              // Special case: ismp-parachain is at modules/ismp/clients/parachain/client
              path = 'modules/ismp/clients/parachain/client';
            } else if (source.crateName.startsWith('ismp-')) {
              // Other ismp-* crates
              const suffix = source.crateName.replace(/^ismp-/, '');
              path = `modules/ismp/clients/${suffix}`;
            }
          }
        }

        // Build URL using actual repo and ref from Cargo.lock
        if (path) {
          githubUrl = `https://github.com/${actualRepo}/tree/${actualRef}/${path}`;
        } else {
          githubUrl = `https://github.com/${actualRepo}/tree/${actualRef}`;
        }
      }

      return {
        cratesIo: source.cratesIoUrl,
        docsRs: source.crateName ? `https://docs.rs/crate/${source.crateName}/${source.version || 'latest'}/source/` : undefined,
        github: githubUrl,
        version: source.version,
        commit: source.commit,
        branch: source.branch,
        forkRepo: source.forkRepo,
        instance: source.instance,
        crateName: source.crateName,
      };
    }
    case 'hydradx': {
      // HydraDX pallets: direct GitHub path with actual commit
      const hydradxInfo = getHydradxGitInfo();
      return {
        github: `https://github.com/galacticcouncil/HydraDX-node/tree/${hydradxInfo.commit}/${source.path}`,
        commit: hydradxInfo.commit,
        branch: hydradxInfo.branch,
        instance: source.instance,
        crateName: source.crateName,
      };
    }
    case 'polkadot-sdk': {
      // Use version info from source (already populated from Cargo.lock)
      const crateName = source.crateName || `pallet-${toSnakeCase(palletName).replace(/_/g, '-')}`;
      const ref = source.commit || 'master';
      const repo = source.forkRepo || 'paritytech/polkadot-sdk';
      return {
        cratesIo: `https://crates.io/crates/${crateName}`,
        docsRs: `https://docs.rs/crate/${crateName}/${source.version || 'latest'}/source/`,
        github: `https://github.com/${repo}/tree/${ref}/${source.path}`,
        version: source.version,
        commit: source.commit,
        branch: source.branch,
        forkRepo: source.forkRepo,
        instance: source.instance,
        crateName: crateName,
      };
    }
    case 'orml': {
      // Use version info from source (already populated from Cargo.lock)
      const crateName = source.crateName || `orml-${toSnakeCase(palletName).replace(/_/g, '-')}`;
      const ref = source.commit || 'master';
      const repo = source.forkRepo || 'open-web3-stack/open-runtime-module-library';
      return {
        cratesIo: `https://crates.io/crates/${crateName}`,
        docsRs: `https://docs.rs/crate/${crateName}/${source.version || 'latest'}/source/`,
        github: `https://github.com/${repo}/tree/${ref}/${source.path}`,
        version: source.version,
        commit: source.commit,
        branch: source.branch,
        forkRepo: source.forkRepo,
        instance: source.instance,
        crateName: crateName,
      };
    }
    case 'cumulus': {
      // Use version info from source (already populated from Cargo.lock)
      const crateName = source.crateName || `cumulus-${toSnakeCase(palletName).replace(/_/g, '-')}`;
      const ref = source.commit || 'master';
      const repo = source.forkRepo || 'paritytech/polkadot-sdk';
      return {
        github: `https://github.com/${repo}/tree/${ref}/cumulus/${source.path}`,
        version: source.version,
        commit: source.commit,
        branch: source.branch,
        forkRepo: source.forkRepo,
        instance: source.instance,
        crateName: crateName,
      };
    }
    default: {
      // Unknown pallets default to HydraDX with actual commit
      const hydradxInfo = getHydradxGitInfo();
      return {
        github: `https://github.com/galacticcouncil/HydraDX-node/tree/${hydradxInfo.commit}/${source.path}`,
        commit: hydradxInfo.commit,
        branch: hydradxInfo.branch,
        instance: source.instance,
        crateName: source.crateName,
      };
    }
  }
}

