// =============================================================================
// PALLET DOCUMENTATION FETCHING
// Reads README.md and lib.rs doc comments for each pallet
// - HydraDX pallets: Read from local filesystem
// - External pallets: Fetched from GitHub (raw.githubusercontent.com)
// =============================================================================

interface PalletDocs {
  readme: string | null;  // Full README.md content (cleaned)
  libRs: string | null;   // lib.rs //! doc comments (extracted)
}

// Cache for pre-fetched external pallet docs
const externalDocsCache = new Map<string, PalletDocs>();

/**
 * Fetch documentation from an external GitHub repository.
 * Attempts to fetch both README.md and lib.rs doc comments.
 */
async function fetchExternalPalletDocs(
  repo: string,
  commit: string,
  path: string
): Promise<PalletDocs> {
  const result: PalletDocs = { readme: null, libRs: null };
  if (!path) return result;

  const baseUrl = `https://raw.githubusercontent.com/${repo}/${commit}/${path}`;

  // Try to fetch lib.rs
  try {
    const libRsUrl = `${baseUrl}/src/lib.rs`;
    const response = await fetch(libRsUrl);
    if (response.ok) {
      const content = await response.text();
      result.libRs = extractLibRsDocComments(content);
    }
  } catch {
    // Ignore fetch errors
  }

  // Try to fetch README.md
  try {
    const readmeUrl = `${baseUrl}/README.md`;
    const response = await fetch(readmeUrl);
    if (response.ok) {
      const content = await response.text();
      result.readme = cleanReadmeContent(content);
    }
  } catch {
    // Ignore fetch errors
  }

  return result;
}

/**
 * Pre-fetch documentation for all external pallets in parallel.
 * Called once during initialization to populate externalDocsCache.
 */
async function prefetchExternalPalletDocs(palletNames: string[]): Promise<void> {
  const fetchPromises: Promise<void>[] = [];

  for (const palletName of palletNames) {
    const source = getPalletSource(palletName);

    // Skip HydraDX pallets (we read those locally)
    if (source.repo === 'hydradx') continue;

    // Skip if no path or repo info
    if (!source.path || !source.forkRepo || !source.commit) continue;

    const cacheKey = `${source.forkRepo}/${source.commit}/${source.path}`;
    if (externalDocsCache.has(cacheKey)) continue;

    fetchPromises.push(
      fetchExternalPalletDocs(source.forkRepo, source.commit, source.path)
        .then(docs => {
          externalDocsCache.set(cacheKey, docs);
        })
    );
  }

  if (fetchPromises.length > 0) {
    log.info(`Fetching docs for ${fetchPromises.length} external pallets...`);
    await Promise.all(fetchPromises);
    const withDocs = Array.from(externalDocsCache.values()).filter(d => d.readme || d.libRs).length;
    log.info(`Fetched docs for ${withDocs} external pallets`);
  }
}

/**
 * Get documentation for a pallet.
 * - HydraDX pallets: Read from local repos/hydration-node/
 * - External pallets: Use pre-fetched cache from GitHub
 */
function readPalletDocs(palletName: string): PalletDocs {
  const source = getPalletSource(palletName);
  const result: PalletDocs = { readme: null, libRs: null };

  // For HydraDX pallets, read from local filesystem
  if (source.repo === 'hydradx') {
    // Try README.md
    const readmePath = join(HYDRADX_NODE_PATH, source.path, 'README.md');
    if (existsSync(readmePath)) {
      try {
        const content = readFileSync(readmePath, 'utf-8');
        result.readme = cleanReadmeContent(content);
      } catch {
        // Ignore errors
      }
    }

    // Try lib.rs doc comments
    const libRsPath = join(HYDRADX_NODE_PATH, source.path, 'src/lib.rs');
    if (existsSync(libRsPath)) {
      try {
        const content = readFileSync(libRsPath, 'utf-8');
        result.libRs = extractLibRsDocComments(content);
      } catch {
        // Ignore errors
      }
    }

    return result;
  }

  // For external pallets, use pre-fetched cache
  if (source.forkRepo && source.commit && source.path) {
    const cacheKey = `${source.forkRepo}/${source.commit}/${source.path}`;
    const cached = externalDocsCache.get(cacheKey);
    if (cached) {
      return cached;
    }
  }

  return result;
}

/**
 * Clean up README.md content for display.
 * - Removes title lines (# pallet-name)
 * - Removes license section at the end
 * - Collapses multiple blank lines
 */
function cleanReadmeContent(content: string): string | null {
  const lines = content.split('\n');
  const result: string[] = [];
  let skipLicense = true;

  for (const line of lines) {
    // Skip title line (# pallet-name or # Pallet Name)
    if (line.startsWith('# ') && result.length === 0) {
      continue;
    }
    // Skip ## Pallet header
    if (line.startsWith('## ') && line.toLowerCase().includes('pallet') && result.length === 0) {
      continue;
    }
    // Skip license section at the end
    if (line.toLowerCase().startsWith('license')) {
      break;
    }
    // Start capturing after we see real content
    if (line.trim()) {
      skipLicense = false;
    }
    if (!skipLicense) {
      result.push(line);
    }
  }

  if (result.length === 0) return null;

  // Clean up: collapse multiple blank lines
  let cleaned = result.join('\n');
  cleaned = cleaned.replace(/\n{3,}/g, '\n\n');
  return cleaned.trim() || null;
}

/**
 * Extract Rust doc comments (//!) from lib.rs.
 * These appear at the top of the file and provide module-level documentation.
 * Converts ## headers to ### to fit within pallet doc hierarchy.
 */
function extractLibRsDocComments(content: string): string | null {
  const lines = content.split('\n');
  const docLines: string[] = [];
  let inDocSection = false;
  let foundDoc = false;

  for (const line of lines) {
    const trimmed = line.trim();

    // Skip license comments (// without !)
    if (trimmed.startsWith('// ') && !trimmed.startsWith('//!')) {
      if (!foundDoc) continue; // Skip initial license block
      else break; // Stop at regular comments after doc comments
    }

    // Doc comments start with //!
    if (trimmed.startsWith('//!')) {
      foundDoc = true;
      inDocSection = true;

      // Empty doc line (just "//!")
      if (trimmed === '//!') {
        docLines.push('');
        continue;
      }

      // Remove the //! prefix
      let docContent = trimmed.slice(3);
      // Preserve leading space for indentation, but trim trailing
      if (docContent.startsWith(' ')) docContent = docContent.slice(1);

      // Skip the main title (e.g., "# Omnipool pallet")
      if (docContent.startsWith('# ') && docLines.length === 0) {
        continue;
      }

      // Convert ## headers to ### (since we're inside pallet doc)
      if (docContent.startsWith('## ')) {
        docContent = '#' + docContent;
      }

      docLines.push(docContent);
      continue;
    }

    // Non-doc line after doc section - we're done
    if (inDocSection && !trimmed.startsWith('//!')) {
      break;
    }

    // Skip #![...] attributes
    if (trimmed.startsWith('#![')) {
      if (foundDoc) break;
      continue;
    }
  }

  if (docLines.length === 0) return null;

  // Clean up: remove excessive blank lines
  const cleanedLines: string[] = [];
  let prevWasBlank = false;

  for (const line of docLines) {
    if (line === '') {
      if (!prevWasBlank && cleanedLines.length > 0) {
        cleanedLines.push('');
        prevWasBlank = true;
      }
    } else {
      cleanedLines.push(line);
      prevWasBlank = false;
    }
  }

  return cleanedLines.join('\n').trim() || null;
}

// Clean up docs string for display (escape MDX-sensitive characters)
function cleanDocs(docs: string): string {
  if (!docs) return '';

  let result = docs;

  // Remove rustdoc relative links like [text](./trait.Config.html) or [text](../pallet_foo/index.html)
  // These don't work in the docs site context
  result = result.replace(
    /\[([^\]]+)\]\((?:\.\/|\.\.\/)[^)]*\.html[^)]*\)/g,
    '`$1`'  // Convert to inline code instead
  );

  // Remove rustdoc links to .html files (trait.Config.html, enum.Call.html, etc.)
  result = result.replace(
    /\[([^\]]+)\]\((?!https?:\/\/)[^)]*\.html[^)]*\)/g,
    '`$1`'
  );

  // Remove standalone rustdoc paths like `design-goals` that would be resolved as relative links
  result = result.replace(
    /\[([^\]]+)\]\((?!https?:\/\/|\/|#)([a-z][a-z0-9_-]*)\)/gi,
    '`$1`'
  );

  // Remove backtick links that look like rustdoc paths: [`Config::HistoryDepth`]
  result = result.replace(
    /\[`([^`]+)`\](?:\([^)]*\))?/g,
    '`$1`'
  );

  // Remove reference-style markdown links: [`Config`]: ./trait.Config.html
  result = result.replace(
    /^\[`?[^\]]+`?\]:\s*(?:\.\/|\.\.\/)?[^\s]+\.html.*$/gm,
    ''
  );

  // Remove reference-style links to non-URL targets: [Config]: design-goals
  result = result.replace(
    /^\[`?[^\]]+`?\]:\s*(?!https?:\/\/)[^\s]+$/gm,
    ''
  );

  // First, convert URLs in angle brackets to markdown links: <https://...> -> [link](url)
  result = result.replace(/<(https?:\/\/[^>]+)>/g, (_match, url) => {
    // Create a short display text from the URL
    const displayUrl = url.length > 60 ? url.substring(0, 57) + '...' : url;
    return `[${displayUrl}](${url})`;
  });

  // Handle code blocks: ```lang ... ``` -> proper markdown code blocks
  // These can appear inline in the docs, need to format them properly
  result = result.replace(/```(\w*)\s+([\s\S]*?)```/g, (_match, lang, code) => {
    const cleanCode = code.trim();
    return `\n\n\`\`\`${lang}\n${cleanCode}\n\`\`\`\n\n`;
  });

  // Handle `backtick code` - escape MDX chars inside backticks carefully
  // First, temporarily protect backtick content
  const backtickProtected: string[] = [];
  result = result.replace(/`([^`]+)`/g, (_match, code) => {
    backtickProtected.push(code);
    return `__BACKTICK_${backtickProtected.length - 1}__`;
  });

  // Now escape MDX-sensitive characters in remaining text
  result = result
    .replace(/</g, '\\<')
    .replace(/>/g, '\\>')
    .replace(/\{/g, '\\{')
    .replace(/\}/g, '\\}');

  // Restore backtick content (don't escape inside backticks)
  result = result.replace(/__BACKTICK_(\d+)__/g, (_match, idx) => {
    return '`' + backtickProtected[parseInt(idx)] + '`';
  });

  // Clean up whitespace - normalize but preserve intentional line breaks
  result = result
    .replace(/\n{3,}/g, '\n\n')  // Max 2 newlines
    .replace(/[ \t]+/g, ' ')     // Normalize horizontal whitespace
    .trim();

  return result;
}

// Format type as Rust-like syntax with multi-line for complex types
function formatRustType(type: string): string {
  // Clean up the type string
  const cleaned = type
    .replace(/"/g, '')  // Remove JSON quotes
    .replace(/\s+/g, ' ')  // Normalize whitespace
    .trim();

  // Check if this contains a struct with many fields: {...}
  const braceStart = cleaned.indexOf('{');
  const braceEnd = cleaned.lastIndexOf('}');

  if (braceStart !== -1 && braceEnd > braceStart) {
    const prefix = cleaned.substring(0, braceStart);
    const structContent = cleaned.substring(braceStart + 1, braceEnd);
    const suffix = cleaned.substring(braceEnd + 1);

    // Parse fields
    const fieldPairs = parseStructFields(structContent);

    // If more than 2 fields, format on multiple lines
    if (fieldPairs.length > 2) {
      const formattedFields = fieldPairs
        .map(f => `    ${f.name}: ${f.type},`)
        .join('\n');
      return `${prefix}{\n${formattedFields}\n}${suffix}`;
    }
  }

  // For simpler types, just clean up spacing
  return cleaned
    .replace(/,/g, ', ')
    .replace(/:(?!\s)/g, ': ');
}

// Parse struct fields from a string like "name:Type,other:Type2"
function parseStructFields(fieldsStr: string): { name: string; type: string }[] {
  const fields: { name: string; type: string }[] = [];
  let depth = 0;
  let current = '';

  for (const char of fieldsStr) {
    if (char === '{' || char === '<' || char === '(') depth++;
    else if (char === '}' || char === '>' || char === ')') depth--;

    if (char === ',' && depth === 0) {
      const parsed = parseField(current.trim());
      if (parsed) fields.push(parsed);
      current = '';
    } else {
      current += char;
    }
  }

  // Don't forget the last field
  if (current.trim()) {
    const parsed = parseField(current.trim());
    if (parsed) fields.push(parsed);
  }

  return fields;
}

// Parse a single field like "name:Type" or "name: Type"
function parseField(field: string): { name: string; type: string } | null {
  const colonIdx = field.indexOf(':');
  if (colonIdx === -1) return null;
  return {
    name: field.substring(0, colonIdx).trim(),
    type: field.substring(colonIdx + 1).trim(),
  };
}

function generatePalletMdx(
  pallet: PalletMetadata,
  hooks: { name: string; category: string }[],
  entities: string[],
  sdkRefs: { package: string; method: string }[],
  storageToSDK: Map<string, Array<{ method: string; package: string }>>,
  metadata: ChainMetadata,
  detailed?: DetailedPalletMetadata,
  handlerIndex?: Map<string, { event: string; file: string; line: number }>,
  indexerSource?: { repo: string; commit: string } | null,
  eventToHandlerMap?: Record<string, { handlers: string[]; entities: string[] }>,
  validEntityNames?: Set<string>
): string {
  const palletLinks = buildPalletLinks(pallet.name);
  const subscanLink = buildSubscanLink(pallet.name);
  const sourceLabel = getSourceLabel(pallet.name);
  const palletDocs = readPalletDocs(pallet.name);

  const lines: string[] = [
    '---',
    `title: ${pallet.name}`,
    `description: Runtime pallet documentation`,
    `sidebar_label: ${pallet.name}`,
    '---',
    '',
    `# ${pallet.name}`,
    '',
  ];

  // Add README content if available
  if (palletDocs.readme) {
    lines.push(cleanDocs(palletDocs.readme));
    lines.push('');
  }

  // Add lib.rs doc comments in a collapsible section if available
  if (palletDocs.libRs) {
    lines.push('<details>');
    lines.push('<summary>Code Documentation</summary>');
    lines.push('');
    lines.push(cleanDocs(palletDocs.libRs));
    lines.push('');
    lines.push('</details>');
    lines.push('');
  }

  // Add AI placeholder for additional/missing descriptions
  lines.push('<!-- AI_DESCRIPTION_START -->');
  if (!palletDocs.readme && !palletDocs.libRs) {
    lines.push(`> **TODO**: AI-generated description of what this pallet does.`);
  }
  lines.push('<!-- AI_DESCRIPTION_END -->');
  lines.push('');

  // Calculate counts for section headers
  const storageCount = detailed ? detailed.storage.length : pallet.storage.length;
  const callsCount = detailed
    ? detailed.calls.filter(c => !c.name.startsWith('__Unused')).length
    : pallet.calls.length;
  const eventsCount = detailed ? detailed.events.length : pallet.events.length;
  const constantsCount = detailed ? detailed.constants.length : pallet.constants.length;

  // Quick Reference - two lines for readability
  // Build crate/commit/branch string
  const cratePart = palletLinks.crateName || pallet.name.toLowerCase();
  const commitPart = palletLinks.commit ? palletLinks.commit.substring(0, 8) : '';
  const branchPart = palletLinks.branch || '';
  const instancePart = palletLinks.instance ? ` (${palletLinks.instance})` : '';

  let crateInfo: string;
  if (commitPart && branchPart) {
    crateInfo = `\`${cratePart}/${commitPart}/${branchPart}\`${instancePart}`;
  } else if (commitPart) {
    crateInfo = `\`${cratePart}/${commitPart}\`${instancePart}`;
  } else {
    crateInfo = `\`${cratePart}\`${instancePart}`;
  }

  lines.push(`**Pallet #${pallet.index}** · ${sourceLabel}<br/>`);
  lines.push(crateInfo);
  lines.push('');

  // Links line
  const linkParts: string[] = [];
  linkParts.push(`[GitHub](${palletLinks.github})`);
  if (palletLinks.docsRs) {
    linkParts.push(`[docs.rs](${palletLinks.docsRs})`);
  }
  if (palletLinks.cratesIo) {
    linkParts.push(`[crates.io](${palletLinks.cratesIo})`);
  }
  linkParts.push(`[Subscan](${subscanLink})`);
  lines.push(linkParts.join(' · '));
  lines.push('');

  // Storage section with Rust code blocks
  if (detailed && detailed.storage.length > 0) {
    lines.push(`## Storage (${storageCount})`);
    lines.push('');
    for (const storage of detailed.storage) {
      const rustType = formatRustType(storage.type);
      const docs = cleanDocs(storage.docs);
      lines.push(`### ${storage.name}`);
      lines.push('');
      if (docs) {
        lines.push(docs);
        lines.push('');
      }
      lines.push('```rust');
      lines.push(`${storage.name}: ${rustType}`);
      lines.push('```');
      lines.push('');

      // Show SDK methods that read this storage - with links to SDK docs
      const storageKey = `${pallet.name.toLowerCase()}.${storage.name.toLowerCase()}`;
      const sdkMethods = storageToSDK.get(storageKey);
      if (sdkMethods && sdkMethods.length > 0) {
        // Create linked method names: [ClassName.method](/reference/sdk/package#classname)
        const linkedMethods = sdkMethods.map(m => {
          const className = m.method.includes('.') ? m.method.split('.')[0] : '';
          const anchor = className ? `#${className.toLowerCase()}` : '';
          return `[${m.method}](/reference/sdk/${m.package}${anchor})`;
        });
        lines.push(`**Read by SDK:** ${linkedMethods.join(', ')}`);
        lines.push('');
      }
    }
  } else if (pallet.storage.length > 0) {
    lines.push(`## Storage (${storageCount})`);
    lines.push('');
    lines.push('```rust');
    for (const storage of pallet.storage) {
      const name = storage.replace(`${pallet.name}.`, '');
      lines.push(name);
    }
    lines.push('```');
    lines.push('');
  }

  // Calls (Extrinsics) section with Rust signatures
  if (detailed && detailed.calls.length > 0) {
    const realCalls = detailed.calls.filter(c => !c.name.startsWith('__Unused'));
    if (realCalls.length > 0) {
      lines.push(`## Extrinsics (${callsCount})`);
      lines.push('');
      for (const call of realCalls) {
        const docs = cleanDocs(call.docs);
        lines.push(`### ${call.name}`);
        lines.push('');
        if (docs) {
          lines.push(docs);
          lines.push('');
        }
        lines.push('```rust');
        if (call.args.length === 0) {
          lines.push(`fn ${call.name}(origin: OriginFor<T>)`);
        } else {
          lines.push(`fn ${call.name}(`);
          lines.push('    origin: OriginFor<T>,');
          for (const arg of call.args) {
            lines.push(`    ${arg.name}: ${arg.type},`);
          }
          lines.push(')');
        }
        lines.push('```');
        lines.push('');
      }
    }
  } else if (pallet.calls.length > 0) {
    lines.push(`## Extrinsics (${callsCount})`);
    lines.push('');
    lines.push('```rust');
    for (const call of pallet.calls) {
      const name = call.replace(`${pallet.name}.`, '');
      lines.push(`fn ${name}(origin: OriginFor<T>, ...)`);
    }
    lines.push('```');
    lines.push('');
  }

  // Events section with Rust structs
  if (detailed && detailed.events.length > 0) {
    lines.push(`## Events (${eventsCount})`);
    lines.push('');
    for (const event of detailed.events) {
      const docs = cleanDocs(event.docs);
      lines.push(`### ${event.name}`);
      lines.push('');
      if (docs) {
        lines.push(docs);
        lines.push('');
      }
      if (event.fields.length > 0) {
        lines.push('```rust');
        lines.push(`${event.name} {`);
        for (const field of event.fields) {
          if (field.name) {
            lines.push(`    ${field.name}: ${field.type},`);
          } else {
            lines.push(`    ${field.type},`);
          }
        }
        lines.push('}');
        lines.push('```');
      } else {
        lines.push('```rust');
        lines.push(`${event.name}`);
        lines.push('```');
      }
      // Add indexer handler link if this event is indexed
      const fullEventName = `${pallet.name}.${event.name}`;
      const eventMapping = eventToHandlerMap?.[fullEventName];
      if (eventMapping && eventMapping.entities.length > 0) {
        // Filter to only valid entity names (not enum types)
        const validEntities = validEntityNames?.size
          ? eventMapping.entities.filter(e => validEntityNames.has(e))
          : eventMapping.entities;
        if (validEntities.length > 0) {
          lines.push('');
          const entityLinks = validEntities.map(e => `[${e}](/reference/indexer/${e})`).join(', ');
          lines.push(`**Indexed by:** ${entityLinks}`);
        }
      }
      lines.push('');
    }
  } else if (pallet.events.length > 0) {
    lines.push(`## Events (${eventsCount})`);
    lines.push('');
    lines.push('```rust');
    for (const event of pallet.events) {
      const name = event.replace(`${pallet.name}.`, '');
      lines.push(name);
    }
    lines.push('```');
    lines.push('');
  }

  // Constants section with Rust code blocks
  if (detailed && detailed.constants.length > 0) {
    lines.push(`## Constants (${constantsCount})`);
    lines.push('');
    for (const constant of detailed.constants) {
      const docs = cleanDocs(constant.docs);
      lines.push(`### ${constant.name}`);
      lines.push('');
      if (docs) {
        lines.push(docs);
        lines.push('');
      }
      lines.push('```rust');
      lines.push(`const ${constant.name}: ${constant.type}`);
      lines.push('```');
      lines.push('');
    }
  } else if (pallet.constants.length > 0) {
    lines.push(`## Constants (${constantsCount})`);
    lines.push('');
    lines.push('```rust');
    for (const constant of pallet.constants) {
      const name = constant.replace(`${pallet.name}.`, '');
      lines.push(`const ${name}`);
    }
    lines.push('```');
    lines.push('');
  }

  // References section (cross-references to other layers)
  if (entities.length > 0 || hooks.length > 0 || sdkRefs.length > 0) {
    lines.push(`## References`);
    lines.push('');

    // SDK packages that use this pallet
    if (sdkRefs.length > 0) {
      // Get unique packages
      const uniquePackages = [...new Set(sdkRefs.map(r => r.package))];
      lines.push(`### SDK (${uniquePackages.length})`);
      lines.push('');
      for (const pkg of uniquePackages) {
        lines.push(`- [${pkg}](/reference/sdk/${pkg})`);
      }
      lines.push('');
    }

    // Indexer entities
    if (entities.length > 0) {
      // Separate entities from handlers
      const regularEntities = entities.filter(e => !e.startsWith('handler:'));

      if (regularEntities.length > 0) {
        lines.push(`### Indexer (${regularEntities.length})`);
        lines.push('');
        for (const entity of regularEntities) {
          lines.push(`- [${entity}](/reference/indexer/${entity})`);
        }
        lines.push('');
      }
    }

    // UI hooks
    if (hooks.length > 0) {
      lines.push(`### UI (${hooks.length})`);
      lines.push('');
      for (const hook of hooks) {
        lines.push(`- [${hook.name}](/reference/hooks/${hook.category}/${hook.name})`);
      }
      lines.push('');
    }
  }

  return lines.join('\n');
}

