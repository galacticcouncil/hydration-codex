// Cache for workspace member paths fetched from remote Cargo.toml files
// =============================================================================
// WORKSPACE MEMBERS CACHE
// Fetches Cargo.toml from external repos to get exact crate paths
// Uses [workspace.dependencies] for direct crate-name -> path mapping
// =============================================================================

const workspaceMembersCache: Map<string, Map<string, string>> = new Map();

/**
 * Fetch workspace Cargo.toml and parse crate paths.
 * Prioritizes [workspace.dependencies] which has explicit crate-name = { path = "..." } mappings.
 * Falls back to [workspace] members for crates not in dependencies.
 */
async function fetchWorkspaceMembers(repo: string, branch: string): Promise<Map<string, string>> {
  const cacheKey = `${repo}@${branch}`;
  if (workspaceMembersCache.has(cacheKey)) {
    return workspaceMembersCache.get(cacheKey)!;
  }

  const crateToPath = new Map<string, string>();

  try {
    const url = `https://raw.githubusercontent.com/${repo}/${branch}/Cargo.toml`;
    log.info(`Fetching workspace members from ${repo}...`);

    const response = await fetch(url);
    if (!response.ok) {
      log.warn(`Failed to fetch ${url}: ${response.status}`);
      workspaceMembersCache.set(cacheKey, crateToPath);
      return crateToPath;
    }

    const content = await response.text();

    // Parse [workspace.dependencies] which has explicit crate-name = { path = "..." } mappings
    // This is more reliable than deriving names from directory paths
    const depsMatch = content.match(/\[workspace\.dependencies\]([\s\S]*?)(?:\n\[|\n$)/);
    if (depsMatch) {
      // Match patterns like: crate-name = { path = "path/to/crate", ... }
      const depMatches = depsMatch[1].matchAll(/^([a-zA-Z0-9_-]+)\s*=\s*\{[^}]*path\s*=\s*"([^"]+)"/gm);
      for (const match of depMatches) {
        const crateName = match[1];
        const path = match[2];
        crateToPath.set(crateName, path);
      }
    }

    // Also parse workspace members for crates not in dependencies
    const membersMatch = content.match(/\[workspace\][\s\S]*?members\s*=\s*\[([\s\S]*?)\]/);
    if (membersMatch) {
      const membersContent = membersMatch[1];
      const pathMatches = membersContent.matchAll(/"([^"]+)"/g);

      for (const match of pathMatches) {
        const path = match[1];
        if (path.includes('*')) continue; // Skip glob patterns

        // Derive crate name from last path segment
        const segments = path.split('/');
        const lastName = segments[segments.length - 1];

        // Only add if not already in the map (dependencies take priority)
        if (!crateToPath.has(lastName)) {
          crateToPath.set(lastName, path);
        }
      }
    }

    log.info(`Found ${crateToPath.size} crate paths in ${repo}`);
  } catch (err) {
    log.warn(`Error fetching workspace for ${repo}: ${err}`);
  }

  workspaceMembersCache.set(cacheKey, crateToPath);
  return crateToPath;
}

// Synchronous version using pre-fetched cache
function getWorkspacePath(repo: string, ref: string, crateName: string): string | undefined {
  const cacheKey = `${repo}@${ref}`;
  const members = workspaceMembersCache.get(cacheKey);
  if (!members) return undefined;

  // Direct lookup by crate name (from [workspace.dependencies])
  if (members.has(crateName)) {
    return members.get(crateName);
  }

  // Fallback: try directory name derived from crate name
  const shortName = crateName
    .replace(/^cumulus-pallet-/, '')
    .replace(/^pallet-/, '')
    .replace(/^orml-/, '');

  if (members.has(shortName)) {
    return members.get(shortName);
  }

  return undefined;
}

